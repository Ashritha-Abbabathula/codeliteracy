"""FR4: alongside the flowchart, produce a plain-language explanation of what each
file/module does and how the pieces connect - generated by the LLM from the actual
source, not just filenames."""

import json
from pathlib import Path

from app.services.dependency_graph import Graph
from app.services.llm_client import LLMCallError, LLMNotConfiguredError, json_completion

# Keep prompt size (and LLM cost) bounded: explain the most structurally important
# files first - the ones with the most in/out edges are the ones most worth
# understanding before touching the code.
MAX_FILES_EXPLAINED = 40
MAX_CHARS_PER_FILE = 2000

_SYSTEM_PROMPT = """\
You are CodeLiteracy's repository explainer. You help a developer who has never seen \
this codebase before build an accurate mental model of it, fast. You are given a \
Python repository's file list, the import relationships between those files, and \
(truncated) source for each file. Respond with strict JSON only, matching exactly:

{"overview": "2-4 sentence plain-language walkthrough of the repo's overall structure \
and how the main pieces fit together", \
"files": [{"path": "relative/path.py", "explanation": "one or two plain-language \
sentences on what this specific file does, grounded in its actual code"}]}

Do not use unexplained jargon. Do not wrap the JSON in markdown fences."""


class ExplanationError(Exception):
    pass


def _rank_files_by_importance(graph: Graph) -> list[str]:
    degree: dict[str, int] = {node["id"]: 0 for node in graph.nodes}
    for edge in graph.edges:
        degree[edge["source"]] = degree.get(edge["source"], 0) + 1
        degree[edge["target"]] = degree.get(edge["target"], 0) + 1
    return sorted(degree, key=lambda path: degree[path], reverse=True)


def _build_prompt(repo_path: str, graph: Graph) -> str:
    root = Path(repo_path)
    ranked_paths = _rank_files_by_importance(graph)[:MAX_FILES_EXPLAINED]
    ranked_set = set(ranked_paths)

    file_sections = []
    for rel_path in ranked_paths:
        try:
            content = (root / rel_path).read_text(encoding="utf-8", errors="ignore")
        except OSError:
            content = ""
        truncated = content[:MAX_CHARS_PER_FILE]
        if len(content) > MAX_CHARS_PER_FILE:
            truncated += "\n# ... truncated ..."
        file_sections.append(f"### {rel_path}\n```python\n{truncated}\n```")

    edges_desc = "\n".join(
        f"- {e['source']} imports from {e['target']}"
        for e in graph.edges
        if e["source"] in ranked_set and e["target"] in ranked_set
    )

    omitted_note = ""
    if len(graph.nodes) > len(ranked_paths):
        omitted_note = (
            f"\n\n({len(graph.nodes) - len(ranked_paths)} additional, less-connected "
            "files were omitted for brevity.)"
        )

    return (
        f"Repository has {len(graph.nodes)} Python files. Import relationships:\n"
        f"{edges_desc or '(no intra-repo imports detected)'}\n\n"
        f"File contents:\n\n" + "\n\n".join(file_sections) + omitted_note
    )


_SINGLE_FILE_SYSTEM_PROMPT = """\
You are CodeLiteracy's repository explainer. Explain what this one file does to a \
developer who has never seen it before, grounded in its actual code. Respond with \
strict JSON only, matching exactly: {"explanation": "one or two plain-language \
sentences"}. Do not wrap the JSON in markdown fences."""


def generate_file_explanation(repo_path: str, rel_path: str) -> str:
    """On-demand explanation for a single file - used when a file was left out of the
    batched explanation (MAX_FILES_EXPLAINED) because it isn't well-connected in the
    dependency graph, but the user clicked it anyway."""
    root = Path(repo_path).resolve()
    target = (root / rel_path).resolve()
    if root not in target.parents and target != root:
        raise ExplanationError(f"Refused to read path outside the repo: {rel_path}")

    try:
        content = target.read_text(encoding="utf-8", errors="ignore")
    except OSError as exc:
        raise ExplanationError(f"Could not read '{rel_path}': {exc}") from exc

    truncated = content[:MAX_CHARS_PER_FILE]
    if len(content) > MAX_CHARS_PER_FILE:
        truncated += "\n# ... truncated ..."
    prompt = f"### {rel_path}\n```python\n{truncated}\n```"

    try:
        raw_text = json_completion(_SINGLE_FILE_SYSTEM_PROMPT, prompt, max_tokens=256)
    except (LLMNotConfiguredError, LLMCallError) as exc:
        raise ExplanationError(str(exc)) from exc

    try:
        parsed = json.loads(raw_text)
    except json.JSONDecodeError as exc:
        raise ExplanationError("The explainer LLM returned a response that wasn't valid JSON.") from exc

    if "explanation" not in parsed:
        raise ExplanationError("The explainer LLM response was missing the 'explanation' field.")
    return parsed["explanation"]


def generate_explanations(repo_path: str, graph: Graph) -> dict:
    if not graph.nodes:
        return {"overview": "This repository has no Python files to explain.", "files": []}

    try:
        raw_text = json_completion(_SYSTEM_PROMPT, _build_prompt(repo_path, graph), max_tokens=4096)
    except (LLMNotConfiguredError, LLMCallError) as exc:
        raise ExplanationError(str(exc)) from exc

    try:
        parsed = json.loads(raw_text)
    except json.JSONDecodeError as exc:
        raise ExplanationError("The explainer LLM returned a response that wasn't valid JSON.") from exc

    if "overview" not in parsed or "files" not in parsed:
        raise ExplanationError("The explainer LLM response was missing expected fields.")
    return parsed
